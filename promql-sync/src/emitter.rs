/// Convenience: load both sidecar files and the upstream grammar from
/// `upstream_dir`, emit, and return the result. Used by the CLI.
pub fn emit_from_paths(upstream_y: &std::path::Path, sidecar: &Sidecar) -> Result<EmitResult> {
    let src = std::fs::read_to_string(upstream_y)
        .with_context(|| format!("read {}", upstream_y.display()))?;
    let g = crate::yacc::parse(&src).context("parse upstream grammar")?;
    emit(&g, sidecar)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// End-to-end: run the generator against the committed upstream
    /// grammar and committed sidecars. Catches regressions in the
    /// parser, sidecar loader, or emitter; doesn't assert the exact
    /// output (the sidecar is still being filled in) but insists on a
    /// plausibly-shaped grammar.
    #[test]
    fn regenerates_against_real_upstream() {
        let base = locate_crate_dir();
        let sc = Sidecar::load(
            &base.join("grammar-actions.toml"),
            &base.join("grammar-tokens.toml"),
        )
        .expect("load sidecars");
        let result = emit_from_paths(&base.join("upstream/generated_parser.y"), &sc).expect("emit");

        // Output leads with the DO-NOT-EDIT banner, then the grmtools
        // preamble (start + precedence), then rules.
        assert!(
            result.text.starts_with("// Code generated by promql-sync"),
            "{}",
            &result.text[..200]
        );
        assert!(result.text.contains("\n%start expr\n"));
        assert!(result.text.contains("%left"));
        assert!(result.text.contains("%%\n"));

        // Binary expression rule with operator-per-alt shape.
        assert!(
            result.text.contains("binary_expr -> Result<Expr, ()>"),
            "binary_expr rule missing or wrong return type"
        );
        assert!(result.text.contains("expr 'ADD' bin_modifier expr"));

        // At least the rules we've mapped should have emitted.
        for rule in &["expr", "binary_expr", "vector_selector", "label_matchers"] {
            assert!(
                result.rules_emitted.iter().any(|r| r == rule),
                "expected rule {rule} in emitted set"
            );
        }

        // Skip-list rules must not appear.
        for rule in &["series_description", "histogram_desc_map"] {
            assert!(
                !result.rules_emitted.iter().any(|r| r == rule),
                "rule {rule} should have been skipped"
            );
        }
    }

    fn locate_crate_dir() -> std::path::PathBuf {
        // Works whether cargo runs the test from the workspace root or
        // from the promql-sync crate directory.
        let p = std::path::PathBuf::from("../promql-parser");
        if p.exists() {
            return p;
        }
        std::path::PathBuf::from("promql-parser")
    }
}
